// Packs dist/ into the Cloudflare Worker in worker/: every file becomes an in-memory
// Data module, so serving never waits on asset storage. Text files are pre-compressed
// (Brotli q11 + gzip -9), and each file's headers are resolved from dist/_headers at
// build time, so Pages and the Worker share one header config. Run after `astro build`.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { brotliCompressSync, constants, gzipSync } from 'node:zlib';

const dist = path.resolve('dist');
const out = path.resolve('.worker');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml',
  '.svg': 'image/svg+xml',
  '.avif': 'image/avif',
  '.webp': 'image/webp',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
};
const COMPRESSIBLE = new Set(['.html', '.css', '.js', '.json', '.txt', '.xml', '.svg']);
// Pages config files: consumed at build time, never served.
const SKIP = new Set(['_headers', '_redirects', '_routes.json']);

// _headers: a URL pattern on its own line, then indented "Name: value" lines.
// '*' matches any run of characters; headers from every matching rule are merged.
const rules = [];
for (const line of readFileSync(path.join(dist, '_headers'), 'utf8').split('\n')) {
  if (!line.trim() || line.trim().startsWith('#')) continue;
  if (!/^\s/.test(line)) {
    const pattern = line.trim().split('*').map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('.*');
    rules.push({ re: new RegExp(`^${pattern}$`), headers: [] });
  } else {
    const i = line.indexOf(':');
    rules.at(-1).headers.push([line.slice(0, i).trim().toLowerCase(), line.slice(i + 1).trim()]);
  }
}
const headersFor = (urlPath) => {
  const headers = {};
  for (const rule of rules) {
    if (!rule.re.test(urlPath)) continue;
    for (const [name, value] of rule.headers) headers[name] = headers[name] ? `${headers[name]}, ${value}` : value;
  }
  return headers;
};

rmSync(out, { recursive: true, force: true });
mkdirSync(path.join(out, 'assets'), { recursive: true });

const files = readdirSync(dist, { recursive: true, withFileTypes: true })
  .filter((entry) => entry.isFile() && !SKIP.has(entry.name))
  .map((entry) => path.relative(dist, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'))
  .sort();

const imports = [];
const entries = [];
let bundled = 0;
files.forEach((file, n) => {
  const ext = path.extname(file).toLowerCase();
  const type = TYPES[ext];
  if (!type) throw new Error(`build-worker: no content type for ${file}`);
  const body = readFileSync(path.join(dist, file));
  // index.html is served at its directory URL, like Pages does.
  const urlPath = `/${file}`.replace(/(^|\/)index\.html$/, '$1');
  const headers = { ...headersFor(urlPath), 'content-type': type, etag: `W/"${createHash('sha256').update(body).digest('hex').slice(0, 16)}"` };

  const variants = { identity: body };
  if (COMPRESSIBLE.has(ext)) {
    headers.vary = 'Accept-Encoding';
    variants.br = brotliCompressSync(body, {
      params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: body.length },
    });
    variants.gzip = gzipSync(body, { level: 9 });
  }
  const refs = {};
  for (const [encoding, data] of Object.entries(variants)) {
    const name = `a${n}_${encoding}`;
    writeFileSync(path.join(out, 'assets', `${name}.bin`), data);
    imports.push(`import ${name} from './assets/${name}.bin';`);
    refs[encoding] = name;
    bundled += data.length;
  }
  const bodies = Object.entries(refs).map(([encoding, name]) => `${encoding}: ${name}`).join(', ');
  entries.push(`  ${JSON.stringify(urlPath)}: { headers: ${JSON.stringify(headers)}, ${bodies} },`);
});

writeFileSync(
  path.join(out, 'manifest.ts'),
  `// Generated by scripts/build-worker.mjs from dist/. Do not edit.
import type { Asset } from '../worker/asset';
${imports.join('\n')}

export const assets: Record<string, Asset> = {
${entries.join('\n')}
};
`,
);
console.log(`build-worker: ${files.length} files → .worker/ (${(bundled / 1024).toFixed(1)} KB of bodies, incl. pre-compressed variants)`);
